#!/usr/bin/env bash

set -e

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
VPLMN_ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"
ENV_FILE="$VPLMN_ROOT/.env"

# This script selects only the SECURITY mode (TLS vs plain HTTP), which chooses
# the *_tls.yaml / *.yaml config suffix for every NF and MUST match on both
# PLMNs (N32 / SBI TLS).
#
# There is no roaming-mode prompt any more. On Open5GS v2.8.0 the core is one
# unified image set for HR, LBO and Non-Roaming — same images, same NF YAMLs.
# The mode is decided at runtime, NOT by how the core is started:
#   * the home subscriber's `lbo_roaming_allowed` flag (seeded in the home DB), and
#   * which PacketRusher config you launch (config_hr_roaming / _lbo_roaming /
#     _non_roaming), which also picks the UE IMSI.
#
# It also does NOT write OPEN5GS_TAG / UPF_IMAGE: docker-compose.yml defaults
# every image to :v2.8.0 (MongoDB excepted), so an empty .env already runs
# v2.8.0. To pin a different build or roll back, set OPEN5GS_TAG in .env as an
# override (e.g. OPEN5GS_TAG=v2.7.6-hr).

echo "======================================="
echo " Open5GS Security Mode Configuration"
echo "======================================="
echo

# -------- Security mode --------
echo "Select Security Mode:"
echo "  1) TLS"
echo "  2) Non-TLS (Plain HTTP)"
read -rp "Enter choice [1-2]: " SECURITY_CHOICE

case "$SECURITY_CHOICE" in
  1)
    SECURITY_MODE="tls"
    SUFFIX="_tls.yaml"
    ;;
  2)
    SECURITY_MODE="plain"
    SUFFIX=".yaml"
    ;;
  *)
    echo "❌ Invalid security mode selection"
    exit 1
    ;;
esac

echo
echo "======================================="
echo " Applying Configuration"
echo "======================================="
echo " Security Mode: $SECURITY_MODE"
echo

# -------- Preserve existing IP/user variables --------
_HPLMN_IP=$(grep -oP '^HPLMN_IP\s*=\s*\K[0-9.]+' "$ENV_FILE" 2>/dev/null || true)
_VPLMN_IP=$(grep -oP '^VPLMN_IP\s*=\s*\K[0-9.]+' "$ENV_FILE" 2>/dev/null || true)
_HPLMN_USER=$(grep -oP '^HPLMN_USER\s*=\s*\K\S+' "$ENV_FILE" 2>/dev/null || true)
_VPLMN_USER=$(grep -oP '^VPLMN_USER\s*=\s*\K\S+' "$ENV_FILE" 2>/dev/null || true)
_PERF_SERVER_IP=$(grep -oP '^PERF_SERVER_IP\s*=\s*\K[0-9.]+' "$ENV_FILE" 2>/dev/null || true)
_PERF_SERVER_USER=$(grep -oP '^PERF_SERVER_USER\s*=\s*\K\S+' "$ENV_FILE" 2>/dev/null || true)

# -------- Write .env --------
cat > "$ENV_FILE" <<EOF
# Generated by set-open5gs-mode.sh - $(date -Iseconds)
# Security: $SECURITY_MODE

HPLMN_IP=$_HPLMN_IP
VPLMN_IP=$_VPLMN_IP
HPLMN_USER=$_HPLMN_USER
VPLMN_USER=$_VPLMN_USER
PERF_SERVER_IP=$_PERF_SERVER_IP
PERF_SERVER_USER=$_PERF_SERVER_USER

NRF_CONFIG=nrf$SUFFIX
SCP_CONFIG=scp$SUFFIX
AMF_CONFIG=amf$SUFFIX
SMF_CONFIG=smf$SUFFIX
UPF_CONFIG=upf$SUFFIX
AUSF_CONFIG=ausf$SUFFIX
UDM_CONFIG=udm$SUFFIX
PCF_CONFIG=pcf$SUFFIX
NSSF_CONFIG=nssf$SUFFIX
BSF_CONFIG=bsf$SUFFIX
UDR_CONFIG=udr$SUFFIX
SEPP_CONFIG=sepp$SUFFIX
EOF

echo "✅ .env file updated successfully!"
echo
echo "Roaming mode (HR / LBO / Non-Roaming) is not set here — it is chosen by the"
echo "subscriber's lbo_roaming_allowed flag and the PacketRusher config you launch."
echo
echo "Next steps:"
echo "  cd $VPLMN_ROOT"
echo "  docker compose up"
echo
