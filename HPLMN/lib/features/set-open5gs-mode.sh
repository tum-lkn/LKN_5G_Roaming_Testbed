#!/usr/bin/env bash

set -e

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
HPLMN_ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"
ENV_FILE="$HPLMN_ROOT/.env"

echo "======================================="
echo " Open5GS Security Mode Configuration"
echo "======================================="
echo

# -------- Security mode selection --------
echo "Select Security Mode:"
echo "  1) TLS"
echo "  2) Non-TLS (Plain HTTP)"
read -rp "Enter choice [1-2]: " SECURITY_CHOICE

case "$SECURITY_CHOICE" in
  1)
    SECURITY_MODE="tls"
    SUFFIX="_tls.yaml"
    ;;
  2)
    SECURITY_MODE="plain"
    SUFFIX=".yaml"
    ;;
  *)
    echo "❌ Invalid security mode selection"
    exit 1
    ;;
esac

echo
echo "======================================="
echo " Applying Configuration"
echo "======================================="
echo " Security Mode: $SECURITY_MODE"
echo

# -------- Write .env --------
_HPLMN_IP=$(grep -oP '^HPLMN_IP\s*=\s*\K[0-9.]+' "$ENV_FILE" 2>/dev/null || true)
_VPLMN_IP=$(grep -oP '^VPLMN_IP\s*=\s*\K[0-9.]+' "$ENV_FILE" 2>/dev/null || true)
cat > "$ENV_FILE" <<EOF
# Generated by set-open5gs-mode.sh - $(date -Iseconds)
# Security: $SECURITY_MODE

HPLMN_IP=$_HPLMN_IP
VPLMN_IP=$_VPLMN_IP

NRF_CONFIG=nrf$SUFFIX
SCP_CONFIG=scp$SUFFIX
AMF_CONFIG=amf$SUFFIX
SMF_CONFIG=smf$SUFFIX
UPF_CONFIG=upf$SUFFIX
AUSF_CONFIG=ausf$SUFFIX
UDM_CONFIG=udm$SUFFIX
PCF_CONFIG=pcf$SUFFIX
NSSF_CONFIG=nssf$SUFFIX
BSF_CONFIG=bsf$SUFFIX
UDR_CONFIG=udr$SUFFIX
SEPP_CONFIG=sepp$SUFFIX
EOF

echo "✅ .env file updated successfully!"
echo
echo "Next steps:"
echo "  cd $HPLMN_ROOT"
echo "  docker compose up"
